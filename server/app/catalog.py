DEFAULT_FALLBACK_VERSIONS = ["latest", "stable", "1.0.0"]


def find_preset(name: str) -> dict | None:
    if not name:
        return None
    key = name.strip().lower()
    for item in PRESET:
        if key in (item["name"].lower(), item["slug"].lower()):
            return item
    for item in PRESET:
        for alias in [a.strip().lower() for a in item["aliases"].split(",") if a.strip()]:
            if key == alias or (len(key) >= 2 and key in alias):
                return item
    return None
